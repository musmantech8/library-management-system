CREATE TABLE lms_categories (
  category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR2(80) NOT NULL,
  CONSTRAINT lms_categories_name_uk UNIQUE (category_name)
);

CREATE TABLE lms_books (
  book_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn             VARCHAR2(20)  NOT NULL,
  title            VARCHAR2(200) NOT NULL,
  author           VARCHAR2(150) NOT NULL,
  category_id      NUMBER        NOT NULL REFERENCES lms_categories (category_id),
  shelf_code       VARCHAR2(20),
  copies_total     NUMBER        DEFAULT 1 NOT NULL,
  copies_available NUMBER        DEFAULT 1 NOT NULL,
  is_active        VARCHAR2(1)   DEFAULT 'Y' NOT NULL,
  CONSTRAINT lms_books_isbn_uk      UNIQUE (isbn),
  CONSTRAINT lms_books_total_ck     CHECK (copies_total >= 1),
  CONSTRAINT lms_books_available_ck CHECK (copies_available BETWEEN 0 AND copies_total),
  CONSTRAINT lms_books_active_ck    CHECK (is_active IN ('Y', 'N'))
);

CREATE INDEX lms_books_category_ix ON lms_books (category_id);

CREATE TABLE lms_members (
  member_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name    VARCHAR2(120) NOT NULL,
  email        VARCHAR2(150) NOT NULL,
  phone        VARCHAR2(30),
  member_since DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  status       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  CONSTRAINT lms_members_email_uk  UNIQUE (email),
  CONSTRAINT lms_members_status_ck CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE TABLE lms_loans (
  loan_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id     NUMBER        NOT NULL REFERENCES lms_books (book_id),
  member_id   NUMBER        NOT NULL REFERENCES lms_members (member_id),
  loan_date   DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  due_date    DATE          NOT NULL,
  return_date DATE,
  fine_amount NUMBER(10,2)  DEFAULT 0 NOT NULL,
  status      VARCHAR2(10)  DEFAULT 'ISSUED' NOT NULL,
  created_by  VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER),
  CONSTRAINT lms_loans_dates_ck  CHECK (due_date >= loan_date),
  CONSTRAINT lms_loans_fine_ck   CHECK (fine_amount >= 0),
  CONSTRAINT lms_loans_status_ck CHECK (status IN ('ISSUED', 'RETURNED'))
);

CREATE INDEX lms_loans_book_ix   ON lms_loans (book_id);
CREATE INDEX lms_loans_member_ix ON lms_loans (member_id, return_date);

-- Issuing a loan takes one copy off the shelf. The book row is locked first,
-- so two people cannot borrow the last copy at the same time.
CREATE OR REPLACE TRIGGER lms_loans_bi
  BEFORE INSERT ON lms_loans
  FOR EACH ROW
DECLARE
  l_available lms_books.copies_available%TYPE;
BEGIN
  SELECT copies_available INTO l_available
    FROM lms_books
   WHERE book_id = :NEW.book_id
     FOR UPDATE;

  IF l_available < 1 THEN
    RAISE_APPLICATION_ERROR(-20301, 'No copies of this book are available.');
  END IF;

  UPDATE lms_books
     SET copies_available = copies_available - 1
   WHERE book_id = :NEW.book_id;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RAISE_APPLICATION_ERROR(-20305, 'Book ' || :NEW.book_id || ' does not exist.');
END;
/

