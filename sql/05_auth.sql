-- Loans: administrators see every loan, normal users see only their own.
CREATE OR REPLACE VIEW lms_loans_v AS
SELECT l.loan_id,
       l.book_id,
       b.title,
       b.author,
       l.member_id,
       m.full_name AS member_name,
       l.loan_date,
       l.due_date,
       l.return_date,
       l.status,
       CASE WHEN l.return_date IS NULL AND TRUNC(SYSDATE) > l.due_date
            THEN TRUNC(SYSDATE) - l.due_date ELSE 0 END AS days_overdue,
       CASE WHEN l.return_date IS NULL
            THEN lms_loan_pkg.fine_for_days(TRUNC(SYSDATE) - l.due_date)
            ELSE l.fine_amount END AS fine_amount
  FROM lms_loans   l
  JOIN lms_books   b ON b.book_id   = l.book_id
  JOIN lms_members m ON m.member_id = l.member_id
 WHERE lms_auth_pkg.is_admin_yn = 'Y'
    OR l.member_id = lms_auth_pkg.current_member_id;

-- Admin-only view for managing accounts (role and active flag).
CREATE OR REPLACE VIEW lms_users_v (
  user_id, username, full_name, email, role, is_active, created_on,
  CONSTRAINT lms_users_v_pk PRIMARY KEY (user_id) RELY DISABLE
) AS
SELECT user_id, username, full_name, email, role, is_active, created_on
  FROM lms_users;

CREATE OR REPLACE TRIGGER lms_users_v_iu
  INSTEAD OF UPDATE ON lms_users_v
  FOR EACH ROW
BEGIN
  lms_auth_pkg.assert_admin;
  UPDATE lms_users
     SET full_name = :NEW.full_name,
         role      = :NEW.role,
         is_active = :NEW.is_active
   WHERE user_id = :OLD.user_id;
END;
/
